#!/usr/bin/env bash
# Refresh charts/xxl-job/files/schema.sql from XXL-JOB's tables_xxl_job.sql at a release tag.
# Called by scripts/bump-chart.sh; can also be run by hand.
#
# Usage: scripts/bump-hooks/xxl-job.sh <version>
#
# Keeps only the CREATE TABLE statements (no CREATE DATABASE/USE, no sample data)
# and makes them idempotent with IF NOT EXISTS. The chart's setup Job seeds its own data.
set -euo pipefail

version=$1
out="charts/xxl-job/files/schema.sql"

sql=$(curl -fsSL "https://raw.githubusercontent.com/xuxueli/xxl-job/$version/doc/db/tables_xxl_job.sql")

{
  echo "-- Tables of XXL-JOB $version, from doc/db/tables_xxl_job.sql (sample data removed)."
  echo "-- Generated by scripts/bump-hooks/xxl-job.sh; do not edit by hand."
  echo
  printf '%s\n' "$sql" |
    awk '/for default data/ { exit } /CREATE TABLE/ { started = 1 } started' |
    sed -E 's/CREATE TABLE `/CREATE TABLE IF NOT EXISTS `/'
} > "$out"

grep -q 'CREATE TABLE IF NOT EXISTS `xxl_job_lock`' "$out" || {
  echo "schema.sql for $version has no xxl_job_lock table; the SQL file layout changed." >&2; exit 1; }
